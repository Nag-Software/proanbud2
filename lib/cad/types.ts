/** Veggens fotavtrykk i planet, med gjæret hjørne mot nabovegger. */
export type WallFootprint = {
  wallId: string
  /** Venstre side sett fra a mot b. */
  left: [Point, Point]
  /** Høyre side sett fra a mot b. */
  right: [Point, Point]
  /** Senterlinjens parameterområde etter gjæring (kan gå utenfor [0, lengde]). */
  uStart: number
  uEnd: number
  length: number
  direction: Point
  normal: Point
}

/** Et rektangulært delstykke av en vegg (mellom/over/under åpninger). */
export type WallPart = {
  /** Parameter langs fotavtrykket, 0–1. */
  t0: number
  t1: number
  /** Høyde relativt veggens bunn. */
  y0: number
  y1: number
  role: "full" | "under" | "over" | "between"
}

export type SolidMesh = {
  positions: number[]
  indices: number[]
}

export type ElementKind =
  | "wall"
  | "opening"
  | "slab"
  | "roof"
  | "column"
  | "space"

/** Et byggbart volum klart for tegning, IFC-eksport og visuell utvelgelse. */
export type ElementSolid = {
  id: string
  elementId: string
  elementKind: ElementKind
  storeyId: string
  materialId: string | null
  mesh: SolidMesh
  /**
   * Satt når volumet er en ren vertikal ekstrudering av et plan-polygon.
   * IFC-eksporten bruker dette til å skrive ekte IfcExtrudedAreaSolid i stedet
   * for en faceted brep.
   */
  extrusion?: {
    profile: Point[]
    /** Bunn og topp i meter over referansenivå (etasje medregnet). */
    z0: number
    z1: number
  }
}

export type SelectionRef =
  | { kind: "wall"; id: string; storeyId: string }
  | { kind: "opening"; id: string; wallId: string; storeyId: string }
  | { kind: "slab"; id: string; storeyId: string }
  | { kind: "roof"; id: string; storeyId: string }
  | { kind: "column"; id: string; storeyId: string }
  | { kind: "space"; id: string; storeyId: string }
