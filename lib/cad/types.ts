/**
 * Datamodell for ProAnbud CAD.
 *
 * Modellen er PARAMETRISK, ikke en trekantsuppe: en vegg er en senterlinje med
 * tykkelse og høyde, et vindu er en posisjon langs veggen. Det er dette som gjør
 * at brukeren kan dra i hva som helst i ettertid, at mengdeuttrekket blir
 * eksakt (ikke estimert fra mesh), og at IFC-eksporten blir ekte BIM-objekter
 * i stedet for døde flater.
 *
 * Enheter: METER overalt, avrundet til millimeter (se roundMm i math.ts).
 * Vinkler: grader.
 * Plan-koordinater: x mot øst, y mot nord. Høyde (z) ligger i `elevation`/
 * `height`-feltene — planet er alltid 2D, høyden er alltid parametrisk.
 */

export type Point = { x: number; y: number }

export type WallType = "exterior" | "interior" | "load_bearing" | "partition"

export type OpeningKind = "door" | "window" | "opening"

export type SlabKind = "floor" | "ceiling" | "deck" | "foundation"

export type RoofKind = "flat" | "mono" | "gable"

export type MaterialCategory =
  | "wall"
  | "floor"
  | "roof"
  | "opening"
  | "structure"
  | "other"

/**
 * En tilordnbar byggevare/arbeidsressurs. Brukeren velger denne på en flate i
 * 3D-visningen, og mengdeuttrekket ganger opp areal/lengde/volum mot den.
 * Kan peke på en rad i bedriftens prisfil, eller stå frittstående.
 */
export type CadMaterial = {
  id: string
  name: string
  category: MaterialCategory
  /** Hex-farge brukt i 3D-visningen. */
  color: string
  /** Enheten mengden regnes ut i: m2 | m | m3 | stk. */
  unit: string
  /** Hvordan mengden utledes fra geometrien. */
  measure: "area" | "length" | "volume" | "count"
  /** Antall enheter per målte enhet (f.eks. 0.5 plater per m²). Default 1. */
  factor: number
  /** Svinn i prosent som legges på i mengdeuttrekket. */
  wastePercent: number
  supplier?: string | null
  nobb?: string | null
  supplierSku?: string | null
  unitPriceNok?: number | null
  notes?: string | null
}

export type Opening = {
  id: string
  kind: OpeningKind
  /** Avstand i meter fra veggens startpunkt (a) til åpningens SENTER. */
  distance: number
  width: number
  height: number
  /** Underkant åpning, meter over veggens bunn. Dør = 0. */
  sill: number
  label?: string | null
  materialId?: string | null
}

export type Wall = {
  id: string
  a: Point
  b: Point
  thickness: number
  height: number
  /** Bunn av vegg, meter over etasjens gulvnivå. */
  baseOffset: number
  type: WallType
  openings: Opening[]
  /** Hovedmateriale (kledning/overflate) brukt i 3D og mengdeuttrekk. */
  materialId?: string | null
  /** Egne materialer per side, når ut- og innside er forskjellige. */
  exteriorMaterialId?: string | null
  interiorMaterialId?: string | null
  locked?: boolean
  label?: string | null
}

export type Slab = {
  id: string
  kind: SlabKind
  outline: Point[]
  thickness: number
  /** Overkant dekke, meter relativt til etasjens gulvnivå. */
  offset: number
  materialId?: string | null
  label?: string | null
  locked?: boolean
}

export type Roof = {
  id: string
  kind: RoofKind
  outline: Point[]
  /** Underkant tak (raft), meter over etasjens gulvnivå. */
  baseHeight: number
  /** Takvinkel i grader. Ignoreres for flatt tak. */
  pitchDeg: number
  /** Mønets/fallets retning i grader (0 = mot øst). */
  directionDeg: number
  thickness: number
  /** Utstikk i meter utenfor omrisset. */
  overhang: number
  materialId?: string | null
  label?: string | null
  locked?: boolean
}

export type Column = {
  id: string
  position: Point
  width: number
  depth: number
  height: number
  baseOffset: number
  rotationDeg: number
  materialId?: string | null
  label?: string | null
  locked?: boolean
}

/**
 * Rom. Omrisset genereres automatisk fra veggene (se rooms.ts), men kan
 * overstyres manuelt — derfor `autoGenerated`.
 */
export type Space = {
  id: string
  name: string
  outline: Point[]
  autoGenerated: boolean
  /** Gulvbelegg/overflate tilordnet rommet. */
  floorMaterialId?: string | null
  wallMaterialId?: string | null
  ceilingMaterialId?: string | null
}

export type Storey = {
  id: string
  name: string
  /** Gulvnivå i meter over terreng/referansenivå. */
  elevation: number
  /** Standard veggehøyde i etasjen. */
  height: number
  walls: Wall[]
  slabs: Slab[]
  roofs: Roof[]
  columns: Column[]
  spaces: Space[]
  visible?: boolean
}

export type BuildingModelMeta = {
  /** Rutenett i meter (snapping). */
  gridSize: number
  /** Byggets rotasjon mot nord, i grader. */
  northAngleDeg: number
  notes?: string | null
  source?: "manual" | "ai" | "import"
  generatedAt?: string | null
  generatedModel?: string | null
  /** KI-ens egne forbehold — vises som banner over editoren. */
  assumptions?: string[]
}

/** Filformater som kan importeres (se lib/cad/import/formats.ts). */
export type ImportFormat =
  | "ifc"
  | "glb"
  | "gltf"
  | "obj"
  | "fbx"
  | "dae"
  | "kmz"
  | "stl"
  | "3ds"
  | "3mf"
  | "ply"
  | "wrl"
  | "dxf"
  | "pdf"
  | "png"
  | "jpg"

/**
 * En importert fil. Den gjøres IKKE om til parametriske vegger: 3D-filer vises
 * som et eget lag i 3D (som du kan måle på), og tegninger (DXF/PDF/bilde) legges
 * under plantegningen i riktig målestokk. Selve fila ligger i storage-bøtta
 * `project_models`; modellen lagrer bare hvor og hvordan den vises.
 */
export type ModelImport = {
  id: string
  /** Filnavnet slik brukeren lastet det opp. */
  name: string
  format: ImportFormat
  kind: "model" | "drawing"
  storagePath: string
  sizeBytes: number
  visible: boolean
  /** 0.1–1. */
  opacity: number
  /**
   * Meter per enhet i fila. Modeller uten fast enhet (OBJ, STL, FBX …) kan være
   * i mm, cm eller m. For PDF/bilde: meter per piksel i den renderte siden,
   * satt ved kalibrering.
   */
  scale: number
  /** Plassering i planet (meter) og rotasjon om loddlinjen (grader). */
  offset: Point
  rotationDeg: number
  /** Høyde over etasje 0 (meter), for 3D-filer. */
  elevation: number
  /**
   * Hvilken akse som er «opp» i fila. glTF, IFC, FBX og Collada er Y-opp (eller
   * rettes av leseren); STL, 3MF og PLY fra CAD er som regel Z-opp.
   */
  upAxis: "y" | "z"
  /** Tegninger hører til en etasje (vises under den). Null = første etasje. */
  storeyId: string | null
  /** PDF: siden som vises (1-basert). */
  page: number
  createdAt: string
}

/** Et punkt i 3D, i planets koordinater: x mot øst, y mot nord, z opp. Meter. */
export type Point3 = { x: number; y: number; z: number }

/** En oppmåling i 3D (to punkter). Lagres, så hele laget ser den samme. */
export type Measurement = {
  id: string
  a: Point3
  b: Point3
  label?: string | null
}

export type BuildingModel = {
  schemaVersion: 1
  name: string
  units: "m"
  storeys: Storey[]
  materials: CadMaterial[]
  meta: BuildingModelMeta
  /** Importerte filer (3D-modeller og tegninger). */
  imports?: ModelImport[]
  /** Oppmålinger i 3D. */
  measurements?: Measurement[]
}

